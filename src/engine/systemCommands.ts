import { ServerConfig, ShellContext, TerminalLine } from '../types/game';
import { txt } from './networkTools';

export function runSystemCommand(
  cmd: string,
  args: string[],
  shell: ShellContext,
  servers: ServerConfig[]
): TerminalLine[] | null {
  const srv = servers.find((s) => s.id === shell.hostId);
  const osName = srv ? srv.os : 'Ubuntu 22.04.3 LTS';
  const kernel = srv ? srv.kernel : 'Linux 5.15.133.1-microsoft-standard-WSL2 x86_64';

  switch (cmd.toLowerCase()) {
    case 'ss': {
      const lines = [txt('Netid  State   Recv-Q  Send-Q  Local Address:Port   Peer Address:Port  Process')];
      if (!srv) {
        lines.push(txt('tcp    LISTEN  0       128     127.0.0.53%lo:53     0.0.0.0:*          users:(("systemd-resolve",pid=412,fd=14))'));
        lines.push(txt('tcp    LISTEN  0       128     0.0.0.0:22           0.0.0.0:*          users:(("sshd",pid=510,fd=3))'));
      } else {
        for (const svc of srv.services) {
          lines.push(
            txt(
              `${svc.protocol.padEnd(7)}LISTEN  0       128     0.0.0.0:${String(svc.port).padEnd(13)}0.0.0.0:*          users:(("${svc.name}",pid=${400 + svc.port},fd=5))`,
              'bright-green'
            )
          );
        }
      }
      return lines;
    }

    case 'resolvectl':
      return [
        txt('Global'),
        txt('         Protocols: -LLMNR -mDNS -DNSOverTLS DNSSEC=no/unsupported'),
        txt('  resolv.conf mode: stub'),
        txt('Link 2 (eth0)'),
        txt('    Current Scopes: DNS'),
        txt('         Protocols: +DefaultRoute -LLMNR -mDNS -DNSOverTLS DNSSEC=no/unsupported'),
        txt('       DNS Servers: 10.10.0.1 127.0.0.53'),
        txt('        DNS Domain: lab'),
      ];

    case 'resolvconf':
      return [
        txt('# Dynamic resolv.conf(5) file for glibc resolver(3) generated by resolvconf(8)'),
        txt('nameserver 127.0.0.53'),
        txt('nameserver 10.10.0.1'),
        txt('search lab'),
      ];

    case 'systemctl': {
      const sub = args[0] || 'list-units';
      if (sub === 'status') {
        const unit = args[1] || 'system';
        return [
          txt(`● ${unit}`, 'bright-green'),
          txt(`     Loaded: loaded (/lib/systemd/system/${unit}.service; enabled; preset: enabled)`),
          txt(`     Active: active (running) since ${new Date().toUTCString()}`),
        ];
      }
      const lines = [
        txt('  UNIT                        LOAD   ACTIVE SUB     DESCRIPTION'),
        txt('  systemd-journald.service    loaded active running Journal Service'),
        txt('  systemd-networkd.service    loaded active running Network Configuration'),
        txt('  systemd-resolved.service    loaded active running Network Name Resolution'),
      ];
      if (srv) {
        for (const svc of srv.services) {
          lines.push(
            txt(`  ${(svc.name + '.service').padEnd(28)}loaded active running ${svc.version}`, 'green')
          );
        }
      }
      return lines;
    }

    case 'journalctl': {
      const lines = [
        txt(`-- Journal begins at ${new Date(Date.now() - 3600000).toISOString().slice(0, 19)} UTC --`),
        txt(`${shell.hostname} systemd[1]: Started System Logging Service.`),
        txt(`${shell.hostname} systemd[1]: Reached target Network is Online.`),
      ];
      if (srv) {
        for (const svc of srv.services) {
          lines.push(txt(`${shell.hostname} ${svc.name}[${400 + svc.port}]: Listening on port ${svc.port}/${svc.protocol}`));
        }
      }
      return lines;
    }

    case 'apt': {
      const sub = args[0] || 'help';
      if (sub === 'update') {
        return [
          txt('Hit:1 http://archive.ubuntu.com/ubuntu jammy InRelease'),
          txt('Hit:2 http://security.ubuntu.com/ubuntu jammy-security InRelease'),
          txt('Reading package lists... Done'),
          txt('All packages are up to date.', 'bright-green'),
        ];
      }
      if (sub === 'list') {
        return [
          txt('Listing... Done'),
          txt('nmap/jammy,now 7.94-1 amd64 [installed]'),
          txt('openssh-client/jammy,now 1:8.9p1 amd64 [installed]'),
          txt('curl/jammy,now 7.81.0 amd64 [installed]'),
          txt('python3/jammy,now 3.10.6 amd64 [installed]'),
        ];
      }
      return [txt(`apt: ${sub} completed (simulated package manager on ${osName}).`)];
    }

    case 'timedatectl': {
      const now = new Date();
      return [
        txt(`               Local time: ${now.toLocaleString()}`),
        txt(`           Universal time: ${now.toUTCString()}`),
        txt(`                 RTC time: ${now.toISOString().slice(0, 19)}`),
        txt(`                Time zone: Asia/Tokyo (JST, +0900)`),
        txt(`System clock synchronized: yes`),
        txt(`              NTP service: active`),
        txt(`          RTC in local TZ: no`),
      ];
    }

    case 'chronyc':
      return [
        txt('Reference ID    : A9FEA97B (ntp.lab.internal)'),
        txt('Stratum         : 3'),
        txt(`Ref time (UTC)  : ${new Date().toUTCString()}`),
        txt('System time     : 0.000142318 seconds fast of NTP time'),
        txt('Last offset     : +0.000018412 seconds'),
        txt('RMS offset      : 0.000120411 seconds'),
        txt('Leap status     : Normal'),
      ];

    case 'snap':
      return [
        txt('Name     Version    Rev    Tracking       Publisher   Notes'),
        txt('bare     1.0        5      latest/stable  canonical✓  base'),
        txt('core22   20240111   1122   latest/stable  canonical✓  base'),
        txt('firefox  124.0.2    4033   latest/stable  mozilla✓    -'),
      ];

    case 'netplan':
      return [
        txt('network:'),
        txt('  version: 2'),
        txt('  renderer: networkd'),
        txt('  ethernets:'),
        txt('    eth0:'),
        txt(`      addresses: [${shell.ip}/24]`),
        txt('      nameservers:'),
        txt('        addresses: [10.10.0.1, 127.0.0.53]'),
      ];

    case 'ufw': {
      if (!srv) {
        return [txt('Status: inactive')];
      }
      const lines = [txt(`Status: ${srv.firewall.idsEnabled ? 'active' : 'inactive'}`, srv.firewall.idsEnabled ? 'bright-green' : 'yellow')];
      if (srv.firewall.idsEnabled) {
        lines.push(txt('To                         Action      From'));
        lines.push(txt('--                         ------      ----'));
        for (const svc of srv.services) {
          lines.push(txt(`${String(svc.port + '/' + svc.protocol).padEnd(27)}${svc.state === 'open' ? 'ALLOW IN' : 'LIMIT IN'}    Anywhere`));
        }
      }
      return lines;
    }

    case 'do-release-upgrade':
      return [
        txt('Checking for a new Ubuntu release'),
        txt('No new release found.'),
      ];

    case 'ubuntu-drivers':
      return [
        txt('udevadm hwdb is deprecated. Use systemd-hwdb instead.'),
        txt('virtual-guest-utils - (virtualized environment)'),
      ];

    case 'pro':
      return [
        txt('SERVICE          ENTITLED  STATUS    DESCRIPTION'),
        txt('esm-apps         yes       disabled  Expanded Security Maintenance for Applications'),
        txt('esm-infra        yes       disabled  Expanded Security Maintenance for Infrastructure'),
        txt('livepatch        yes       disabled  Canonical Livepatch service'),
      ];

    case 'hostnamectl':
      return [
        txt(` Static hostname: ${shell.hostname}`),
        txt(`       Icon name: computer-vm`),
        txt(`         Chassis: vm`),
        txt(`      Machine ID: 7a9f2d8c4e1b44f1a09c8d21e3345001`),
        txt(`Operating System: ${osName}`),
        txt(`          Kernel: ${kernel}`),
        txt(`    Architecture: x86-64`),
      ];

    case 'localectl':
      return [
        txt('System Locale: LANG=ja_JP.UTF-8'),
        txt('    VC Keymap: jp106'),
        txt('   X11 Layout: jp'),
      ];

    case 'loginctl':
      return [
        txt('SESSION  UID USER     SEAT  TTY'),
        txt(`      1 ${String(shell.uid).padEnd(4)} ${shell.user.padEnd(8)} seat0 pts/0`),
        txt('1 sessions listed.'),
      ];

    case 'networkctl':
      return [
        txt('IDX LINK TYPE     OPERATIONAL SETUP'),
        txt('  1 lo   loopback carrier     unmanaged'),
        txt('  2 eth0 ether    routable    configured', 'bright-green'),
        ...(srv?.internalNetwork ? [txt('  3 eth1 ether    routable    configured', 'bright-green')] : []),
      ];

    case 'nmcli':
      return [
        txt('DEVICE  TYPE      STATE      CONNECTION'),
        txt('eth0    ethernet  connected  Wired connection 1', 'bright-green'),
        ...(srv?.internalNetwork ? [txt('eth1    ethernet  connected  Internal-Net', 'bright-green')] : []),
        txt('lo      loopback  unmanaged  --'),
      ];

    default:
      return null;
  }
}
